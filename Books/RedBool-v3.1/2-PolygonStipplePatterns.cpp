void keyboard(unsigned char key, int x, int y) 
{
    // code 
    switch(key) 
    {
    case 27:
        glutLeaveMainLoop(); 
        break; 

    case 'F': 
    case 'f': 
        if(bIsFullScreen==false)
        {
            glutFullScreen(); 
            bIsFullScreen=true; 
        } 
        else 
        {
            glutLeaveFullScreen(); 
            bIsFullScreen=false; 
        } 
        break; 

    default: 
        break; 
    } 
} 

